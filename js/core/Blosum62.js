/**
 * Puntaje BLOSUM62 entre dos aminoácidos (en mayúsculas)
 * @returns {number|null} null si alguno no es un aminoácido estándar
 */
export function puntajeBlosum62(a, b) {
  const i = AMINOACIDOS.indexOf(a);
  const j = AMINOACIDOS.indexOf(b);
  if (i < 0 || j < 0) return null;
  return VALORES[i][j];
}
